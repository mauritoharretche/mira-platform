import { expect, test } from "@playwright/test";

test("procurement-journey", async ({ page }, info) => {
  const project = info.project.name;
  await page.goto("/login");
  await page.getByLabel("Usuario", { exact: true }).fill(`fictional-${project}-procurement-journey`);
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.MIRA_E2E_PASSWORD!);
  await page.getByLabel("Contraseña", { exact: true }).press("Enter");
  await expect(page).toHaveURL(/\/operations\/catalog$/);
  await page.getByRole("navigation").getByRole("link", { name: "Lotes" }).click();
  await expect(page.getByRole("heading", { name: "Inventario por lotes" })).toBeVisible();
  const first = `PROC-FIXTURE-${project}-A`;
  const second = `PROC-FIXTURE-${project}-B`;
  const placeCode = `FIC-${project.toUpperCase()}-SHELF`;
  const lotCode = `FIC-${project.toUpperCase()}-LOT-A`;
  await page.getByLabel("Código de ubicación").fill(placeCode);
  await page.getByLabel("Nombre de ubicación").fill(`Fictional ${project} receiving shelf`);
  await page.getByRole("button", { name: "Crear ubicación" }).click();
  await expect(page.getByRole("status")).toContainText("Ubicación registrada");
  await page.getByLabel("Buscar variante por nombre o SKU").fill(first);
  await page.getByRole("button", { name: "Buscar variantes", exact: true }).click();
  await page.getByLabel("Variante seleccionada").selectOption({ label: `Fictional ${project} purchase · Fictional pack A · SKU ${first}` });
  await expect(page.getByText("0 EACH sin asignación", { exact: false })).toBeVisible();
  await page.getByLabel("Código de lote").fill(lotCode);
  await page.getByLabel("Vencimiento, si corresponde").fill("2099-12-31");
  await page.getByRole("button", { name: "Crear lote" }).click();
  await expect(page.getByRole("status")).toContainText("Lote registrado");
  await page.getByRole("navigation").getByRole("link", { name: "Compras" }).click();
  await expect(page.getByRole("heading", { name: "Compras y abastecimiento" })).toBeVisible();

  await page.getByLabel("Nombre ficticio").fill(`Fictional ${project} Supply Co`);
  await page.getByRole("button", { name: "Crear proveedor" }).click();
  await expect(page.getByRole("status")).toContainText("Proveedor creado");
  await page.getByLabel("Proveedor activo").selectOption({ label: `Fictional ${project} Supply Co` });
  await page.getByLabel("Buscar variante por nombre o SKU").fill(`PROC-FIXTURE-${project}`);
  await page.getByRole("button", { name: "Buscar variantes", exact: true }).click();
  await page.getByLabel("Variante", { exact: true }).selectOption({ label: `Fictional ${project} purchase · Fictional pack A · ${first}` });
  await page.getByLabel("Cantidad EACH", { exact: true }).fill("5");
  await page.getByLabel("Costo unitario ARS", { exact: true }).fill("12.30");
  await page.getByRole("button", { name: "Agregar variante" }).click();
  await page.getByLabel("Variante", { exact: true }).nth(1).selectOption({ label: `Fictional ${project} purchase · Fictional pack B · ${second}` });
  await page.getByLabel("Cantidad EACH", { exact: true }).nth(1).fill("4");
  await page.getByLabel("Costo unitario ARS", { exact: true }).nth(1).fill("3.25");
  await page.getByRole("button", { name: "Crear orden" }).click();
  await expect(page.getByRole("status")).toContainText("Orden creada en borrador");
  await expect(page.getByRole("heading", { name: "Detalle de orden" })).toBeVisible();
  await expect(page.getByText("Total previsto:")).toContainText("ARS 74.50");
  await page.getByRole("button", { name: "Confirmar orden" }).click();
  await expect(page.getByRole("status")).toContainText("Orden confirmada");
  await expect(page.getByRole("heading", { name: "Registrar recepción" })).toBeVisible();

  const receiptGroup = (sku: string) => page.locator("fieldset.proc-line").filter({ hasText: `SKU ${sku}` });
  await receiptGroup(first).getByLabel("Cantidad entregada EACH").fill("2");
  await receiptGroup(first).getByLabel("Cantidad aceptada EACH").fill("2");
  await receiptGroup(second).getByLabel("Cantidad entregada EACH").fill("1");
  await receiptGroup(second).getByLabel("Cantidad aceptada EACH").fill("1");
  await receiptGroup(first).getByRole("button", { name: "Consultar lotes y ubicaciones" }).click();
  await receiptGroup(first).getByLabel("Lote de lo aceptado, si corresponde").selectOption({ label: `${lotCode} · ACTIVE` });
  await receiptGroup(first).getByLabel("Ubicación de lo aceptado, si corresponde").selectOption({ label: `${placeCode} · Fictional ${project} receiving shelf` });
  await page.getByRole("button", { name: "Registrar recepción" }).click();
  await expect(page.getByRole("status")).toContainText("Recepción registrada");
  await expect(page.locator(".badge")).toHaveText("PARTIAL");
  await expect(receiptGroup(first)).toContainText("pendiente 3 EACH");
  await expect(receiptGroup(second)).toContainText("pendiente 3 EACH");

  await page.getByRole("button", { name: "Consultar versión de stock" }).nth(0).click();
  await page.getByRole("button", { name: "Consultar versión de stock" }).nth(1).click();
  await expect(page.getByText("Versión de stock: 1")).toHaveCount(2);
  await receiptGroup(first).getByLabel("Cantidad entregada EACH").fill("3");
  await receiptGroup(first).getByLabel("Cantidad aceptada EACH").fill("3");
  await receiptGroup(second).getByLabel("Cantidad entregada EACH").fill("3");
  await receiptGroup(second).getByLabel("Cantidad aceptada EACH").fill("3");
  await receiptGroup(first).getByRole("button", { name: "Consultar lotes y ubicaciones" }).click();
  await receiptGroup(first).getByLabel("Lote de lo aceptado, si corresponde").selectOption({ label: `${lotCode} · ACTIVE` });
  await receiptGroup(first).getByLabel("Ubicación de lo aceptado, si corresponde").selectOption({ label: `${placeCode} · Fictional ${project} receiving shelf` });
  await page.getByRole("button", { name: "Registrar recepción" }).click();
  await expect(page.getByRole("status")).toContainText("Recepción registrada");
  await expect(page.locator(".badge")).toHaveText("COMPLETE");
  await expect(page.getByRole("row").filter({ hasText: first })).toContainText("5");
  await expect(page.getByRole("row").filter({ hasText: second })).toContainText("4");
  await page.getByRole("button", { name: "Consultar stock" }).nth(0).click();
  await page.getByRole("button", { name: "Consultar stock" }).nth(1).click();
  await expect(page.getByText("5 EACH", { exact: true })).toBeVisible();
  await expect(page.getByText("4 EACH", { exact: true })).toBeVisible();
  await expect(page.getByText(/movimiento de stock/)).toHaveCount(4);
  await page.getByRole("navigation").getByRole("link", { name: "Lotes" }).click();
  await page.getByLabel("Buscar variante por nombre o SKU").fill(first);
  await page.getByRole("button", { name: "Buscar variantes", exact: true }).click();
  await page.getByLabel("Variante seleccionada").selectOption({ label: `Fictional ${project} purchase · Fictional pack A · SKU ${first}` });
  await expect(page.getByText("0 EACH sin asignación", { exact: false })).toBeVisible();
  await expect(page.getByRole("row").filter({ hasText: lotCode })).toContainText("5");
  await page.getByLabel("Motivo de elegibilidad de ubicación").fill("Fictional verified receiving shelf");
  await page.getByRole("button",{name:`Habilitar elegibilidad de ${placeCode}`,exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Elegibilidad de ubicación registrada");
  const commercial=page.getByRole("region",{name:"Disponibilidad y reservas"});
  await commercial.getByLabel("Buscar variante para reserva").fill(first);
  await commercial.getByLabel("Buscar variante para reserva").focus();
  await page.keyboard.press("Tab");
  await expect(commercial.getByRole("button",{name:"Buscar variantes comerciales"})).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(commercial.getByLabel("Buscar variante para reserva")).toBeFocused();
  await commercial.getByRole("button",{name:"Buscar variantes comerciales"}).click();
  await commercial.getByLabel("Variante comercial").selectOption({label:`Fictional ${project} purchase · Fictional pack A · SKU ${first}`});
  await expect(commercial.locator("dl > div").filter({hasText:"Disponible para reservar"})).toContainText("5 EACH");
  await commercial.getByLabel("Cantidad a reservar EACH").fill("2");
  await commercial.getByRole("button",{name:"Agregar variante a reserva"}).click();
  await commercial.getByLabel("Referencia ficticia").fill(`Fictional ${project} release`);
  const expires=new Date(Date.now()+60*60*1000);
  const localExpiry=new Date(expires.getTime()-expires.getTimezoneOffset()*60_000).toISOString().slice(0,16);
  await commercial.getByLabel("Vencimiento de reserva (hora local)").fill(localExpiry);
  await commercial.getByRole("button",{name:"Crear reserva",exact:true}).click();
  await expect(commercial.getByRole("status")).toContainText("ACTIVE");
  await expect(commercial.locator("dl > div").filter({hasText:"Disponible para reservar"})).toContainText("3 EACH");
  await commercial.getByRole("button",{name:"Liberar reserva",exact:true}).click();
  await expect(commercial.getByRole("status")).toContainText("RELEASED");
  await expect(commercial.locator("dl > div").filter({hasText:"Físico"}).first()).toContainText("5 EACH");
  await commercial.getByLabel("Cantidad a reservar EACH").fill("1");
  await commercial.getByRole("button",{name:"Agregar variante a reserva"}).click();
  await commercial.getByLabel("Referencia ficticia").fill(`Fictional ${project} consumption`);
  await commercial.getByRole("button",{name:"Crear reserva",exact:true}).click();
  await expect(commercial.getByRole("status")).toContainText("ACTIVE");
  await commercial.getByRole("button",{name:"Consumir reserva",exact:true}).click();
  await expect(commercial.getByRole("status")).toContainText("CONSUMED");
  await expect(commercial.locator("dl > div").filter({hasText:"Físico"}).first()).toContainText("4 EACH");
  await expect(commercial.getByRole("button",{name:"Consumir reserva",exact:true})).toBeDisabled();
  let writes=0;
  await page.route("**/api/v1/operator/inventory/reservations",async(route)=>{
    if(route.request().method()!=="POST"){await route.continue();return;}
    writes++;
    const response=await route.fetch();
    expect(response.status()).toBe(201);
    await route.abort("failed");
  });
  await commercial.getByLabel("Referencia ficticia").fill(`Fictional ${project} uncertain`);
  await commercial.getByRole("button",{name:"Crear reserva",exact:true}).click();
  await expect(commercial.getByRole("alert").filter({hasText:"Resultado incierto"})).toBeVisible();
  await expect(commercial.getByRole("button",{name:"Crear reserva",exact:true})).toBeDisabled();
  await commercial.getByRole("button",{name:"Consultar resultado de operación"}).click();
  await expect(commercial.getByRole("status")).toContainText("Operación encontrada");
  await expect(commercial.getByRole("button",{name:"Crear reserva",exact:true})).toBeDisabled();
  expect(writes).toBe(1);
  await page.unroute("**/api/v1/operator/inventory/reservations");
  if(project==="mobile") await page.setViewportSize({width:320,height:844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
