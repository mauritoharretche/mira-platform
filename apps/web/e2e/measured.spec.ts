import {expect,test} from "@playwright/test";

test("measured-journey",async({page},info)=>{
  const project=info.project.name;
  const sku=`MEASURED-FIXTURE-${project}`;
  const product=`Fictional ${project} measured`;
  const location=`MASS-${project.toUpperCase()}`;
  const lot=`MASS-LOT-${project.toUpperCase()}`;
  await page.goto("/login");
  await page.getByLabel("Usuario",{exact:true}).fill(`fictional-${project}-measured-journey`);
  await page.getByLabel("Contraseña",{exact:true}).fill(process.env.MIRA_E2E_PASSWORD!);
  await page.getByRole("button",{name:"Iniciar sesión",exact:true}).click();
  await expect(page).toHaveURL(/\/operations\/catalog$/);
  await page.getByLabel("Filtrar productos").selectOption("uncategorized");
  await page.getByRole("link",{name:product,exact:true}).click();
  await page.getByLabel("Presentación / SKU",{exact:true}).selectOption({label:`Fictional measured pack · ${sku}`});
  await expect(page.getByText("Sin precio asignado",{exact:true})).toBeVisible();
  await page.getByLabel("Base de precio",{exact:true}).selectOption("PER_KG");
  await page.getByLabel("Importe ARS por variante").fill("1000,00");
  await page.getByRole("button",{name:"Guardar precio",exact:true}).click();
  await expect(page.locator(".price-panel .stock-count")).toHaveText("ARS 1.000,00");
  await expect(page.locator(".price-panel .workspace-record-block")).toContainText("por KG");
  await page.getByRole("navigation").getByRole("link",{name:"Lotes",exact:true}).click();
  await page.getByLabel("Código de ubicación").fill(location);
  await page.getByLabel("Nombre de ubicación").fill(`Fictional ${project} mass shelf`);
  await page.getByRole("button",{name:"Crear ubicación",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Ubicación registrada");
  await page.getByLabel("Buscar variante por nombre o SKU").fill(sku);
  await page.getByRole("button",{name:"Buscar variantes",exact:true}).click();
  await page.getByLabel("Variante seleccionada").selectOption({label:`${product} · Fictional measured pack · SKU ${sku}`});
  await page.getByLabel("Código de lote").fill(lot);
  await page.getByLabel("Vencimiento, si corresponde").fill("2099-12-31");
  await page.getByRole("button",{name:"Crear lote",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Lote registrado");
  await page.getByLabel("Motivo de elegibilidad de ubicación").fill("Fictional mass location verified");
  await page.getByRole("button",{name:`Habilitar elegibilidad de ${location}`,exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Elegibilidad de ubicación registrada");
  await page.getByRole("navigation").getByRole("link",{name:"Compras",exact:true}).click();
  await page.getByLabel("Nombre ficticio").fill(`Fictional ${project} Mass Supply`);
  await page.getByRole("button",{name:"Crear proveedor",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Proveedor creado");
  await page.getByLabel("Proveedor activo").selectOption({label:`Fictional ${project} Mass Supply`});
  await page.getByLabel("Buscar variante por nombre o SKU").fill(sku);
  await page.getByRole("button",{name:"Buscar variantes",exact:true}).click();
  await page.getByLabel("Variante",{exact:true}).selectOption({label:`${product} · Fictional measured pack · ${sku}`});
  await page.getByLabel("Unidad contable",{exact:true}).selectOption("G");
  await page.getByLabel("Base del costo",{exact:true}).selectOption("PER_KG");
  await page.getByLabel("Cantidad G",{exact:true}).fill("1000.000");
  await page.getByLabel("Costo unitario ARS",{exact:true}).fill("1000.00");
  await page.getByRole("button",{name:"Crear orden",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Orden creada en borrador");
  await expect(page.getByText("Total previsto:")).toContainText("ARS 1000.00");
  await page.getByRole("button",{name:"Confirmar orden",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Orden confirmada");
  for(const quantity of ["245.001","754.999"]){
    if(quantity==="754.999"){
      await page.getByRole("button",{name:"Consultar versión de stock",exact:true}).click();
      await expect(page.getByText("Versión de stock: 1",{exact:true})).toBeVisible();
    }
    await page.getByLabel("Cantidad entregada G",{exact:true}).fill(quantity);
    await page.getByLabel("Cantidad aceptada G",{exact:true}).fill(quantity);
    await page.getByRole("button",{name:"Consultar lotes y ubicaciones",exact:true}).click();
    await page.getByLabel("Lote de lo aceptado, si corresponde").selectOption({label:`${lot} · ACTIVE`});
    await page.getByLabel("Ubicación de lo aceptado, si corresponde").selectOption({label:`${location} · Fictional ${project} mass shelf`});
    await page.getByRole("button",{name:"Registrar recepción",exact:true}).click();
    await expect(page.getByRole("status")).toContainText("Recepción registrada");
    await expect(page.locator(".badge")).toHaveText(quantity==="245.001"?"PARTIAL":"COMPLETE");
  }
  await page.getByRole("navigation").getByRole("link",{name:"Lotes",exact:true}).click();
  await page.getByLabel("Buscar variante por nombre o SKU").fill(sku);
  await page.getByRole("button",{name:"Buscar variantes",exact:true}).click();
  await page.getByLabel("Variante seleccionada").selectOption({label:`${product} · Fictional measured pack · SKU ${sku}`});
  await expect(page.getByRole("region",{name:"Existencia registrada"}).locator("p strong").first()).toHaveText("1000.000 G");
  const commercial=page.getByRole("region",{name:"Disponibilidad y reservas"});
  await commercial.getByLabel("Buscar variante para reserva").fill(sku);
  await commercial.getByRole("button",{name:"Buscar variantes comerciales",exact:true}).click();
  await commercial.getByLabel("Variante comercial").selectOption({label:`${product} · Fictional measured pack · SKU ${sku}`});
  await expect(commercial.locator("dl > div").filter({hasText:"Disponible para reservar"})).toContainText("1000.000 G");
  await commercial.getByLabel("Cantidad a reservar G",{exact:true}).fill("100.000");
  await commercial.getByRole("button",{name:"Agregar variante a reserva",exact:true}).click();
  await commercial.getByLabel("Referencia ficticia").fill(`Fictional ${project} measured consumption`);
  const expires=new Date(Date.now()+3600000);
  await commercial.getByLabel("Vencimiento de reserva (hora local)").fill(new Date(expires.getTime()-expires.getTimezoneOffset()*60000).toISOString().slice(0,16));
  await commercial.getByRole("button",{name:"Crear reserva",exact:true}).click();
  await expect(commercial.getByRole("status")).toContainText("ACTIVE");
  await commercial.getByRole("button",{name:"Consumir reserva",exact:true}).click();
  await expect(commercial.getByRole("status")).toContainText("CONSUMED");
  await expect(commercial.locator("dl > div").filter({hasText:"Físico"}).first()).toContainText("900.000 G");
  const physical=page.getByRole("region",{name:"Conteos físicos y mermas"});
  await physical.getByLabel("Ubicación de conteo",{exact:true}).selectOption({label:location});
  await physical.getByRole("checkbox",{name:new RegExp(lot)}).check();
  await physical.getByRole("button",{name:"Abrir conteo físico",exact:true}).click();
  await expect(physical.getByRole("status")).toContainText("Sesión de conteo abierta");
  await expect(physical.getByText(/Esperado:/)).toHaveCount(0);
  await physical.getByLabel("Motivo de observación").fill("Fictional milligram count discrepancy");
  await physical.getByLabel("Evidencia de conteo").fill("Fictional measured sample");
  await physical.getByLabel(`Observado ${lot} (G)`,{exact:true}).fill("899.500");
  await physical.getByRole("button",{name:"Registrar observación",exact:true}).click();
  await expect(physical.getByRole("status")).toContainText("Observación registrada");
  await physical.getByRole("button",{name:"Revisar conteo",exact:true}).click();
  await expect(physical.getByRole("status")).toContainText("Conteo revisado");
  await physical.getByRole("button",{name:"Consultar detalle de conteo",exact:true}).click();
  await expect(physical.getByText(/Esperado:/)).toContainText("Discrepancia: -0.500 G");
  await physical.getByRole("button",{name:"Completar conteo físico",exact:true}).click();
  await expect(physical.getByRole("status")).toContainText("Conteo completado");
  const stockRead=page.waitForResponse((response)=>response.request().method()==="GET"&&/\/inventory\/variants\/[^/]+\/stock$/.test(new URL(response.url()).pathname));
  await physical.getByRole("button",{name:"Consultar versión para merma",exact:true}).click();
  expect((await stockRead).status()).toBe(200);
  await physical.getByLabel("Lote y ubicación de merma").selectOption({label:`${lot} · ${location} · 899.500 G`});
  await physical.getByLabel("Cantidad de merma (G)").fill("0.250");
  await physical.getByLabel("Motivo de merma",{exact:true}).selectOption("DAMAGE");
  await physical.getByLabel("Evidencia de merma").fill("Fictional documented spill");
  let lossPosts=0;
  await page.route("**/api/v1/operator/inventory/losses",async(route)=>{
    if(route.request().method()!=="POST"){await route.continue();return;}
    lossPosts++;
    const response=await route.fetch();
    expect(response.status()).toBe(201);
    await route.abort("failed");
  });
  try {
    await physical.getByRole("button",{name:"Registrar merma",exact:true}).click();
    await expect(physical.getByRole("alert")).toContainText("Resultado incierto");
    await expect(physical.getByRole("button",{name:"Registrar merma",exact:true})).toBeDisabled();
    await physical.getByRole("button",{name:"Consultar operación física",exact:true}).click();
    await expect(physical.getByRole("status")).toContainText("Operación encontrada: loss");
    await page.getByRole("button",{name:"Consultar estado vigente",exact:true}).click();
    await expect(page.getByRole("region",{name:"Existencia registrada"}).locator("p strong").first()).toHaveText("899.250 G");
    await expect(physical.getByRole("button",{name:"Registrar merma",exact:true})).toBeDisabled();
    expect(lossPosts).toBe(1);
  } finally { await page.unroute("**/api/v1/operator/inventory/losses"); }
  if(project==="mobile")await page.setViewportSize({width:320,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
